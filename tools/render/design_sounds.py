"""Original procedural sound design for PipePanic. No external recordings."""
import argparse
import base64
import json
from pathlib import Path
import wave

import numpy as np

RATE = 24000
ROOT = Path(__file__).resolve().parents[2]
RNG = np.random.default_rng(2711)


def timebase(seconds):
    return np.arange(round(seconds * RATE)) / RATE


def noise(time, low, high):
    """Periodic, softly filtered turbulence. The flow clip loops without a splice."""
    frequencies = np.fft.rfftfreq(len(time), 1 / RATE)
    spectrum = np.fft.rfft(RNG.standard_normal(len(time)))
    high_pass = frequencies**2 / (frequencies**2 + low**2)
    low_pass = 1 / (1 + (frequencies / high)**4)
    texture = np.fft.irfft(spectrum * high_pass * low_pass, n=len(time))
    return texture / max(np.std(texture), 1e-8)


def envelope(time, attack, release):
    return np.clip(time / attack, 0, 1) * np.clip((time[-1] - time) / release, 0, 1)


def ring(time, frequency, decay):
    return np.sin(2 * np.pi * frequency * time) * np.exp(-time / decay)


def water(time, loop=False):
    seconds = len(time) / RATE
    swell = .82 + .11 * np.sin(2 * np.pi * 3 * time / seconds)
    swell += .06 * np.sin(2 * np.pi * 7 * time / seconds + 1.2)
    body = .048 * noise(time, 190, 1150) + .026 * noise(time, 620, 2900)
    body += .014 * noise(time, 1800, 5100)
    sound = body * swell
    for at in RNG.uniform(0, seconds, int(seconds * 10)):
        offset = (time - at) % seconds if loop else time - at
        age = np.maximum(0, offset)
        duration = RNG.uniform(.045, .13)
        pitch = RNG.uniform(430, 1280)
        phase = 2 * np.pi * (pitch * age + 2600 * age**2)
        bubble = np.sin(phase) * np.minimum(age / .009, 1) * np.exp(-age / (duration / 4))
        sound += RNG.uniform(.025, .075) * bubble * ((offset >= 0) & (age < duration))
    return sound


def metal(strength, pitch):
    t = timebase(.16)
    impact = .38 * ring(t, pitch, .021) + .25 * ring(t, pitch * 2.74, .013)
    impact += .19 * noise(t, 650, 3900) * np.exp(-t / .013)
    return strength * np.tanh(impact) * envelope(t, .002, .04)


def make_sounds():
    t = timebase(.55)
    valve = water(t) * (.6 + 2.4 * np.exp(-((t - .12) / .08)**2))
    valve += .20 * ring(t, 410, .04) + .11 * ring(t, 1260, .025)
    valve *= envelope(t, .012, .22)
    t = timebase(.73)
    leak = (.16 * noise(t, 710, 4800) + .5 * water(t)) * np.exp(-t / .22)
    for at in [.08, .16, .29, .43, .55]:
        age = np.maximum(t - at, 0)
        leak += .08 * ring(age, RNG.uniform(550, 1050), .021) * (t >= at)
    leak = np.tanh(leak) * envelope(t, .018, .13)
    t = timebase(.62)
    success = np.zeros_like(t)
    for at, pitch in [(0, 523.25), (.10, 659.25), (.20, 783.99)]:
        age = np.maximum(t - at, 0)
        success += .13 * ring(age, pitch, .10) * np.minimum(age / .008, 1)
    success *= envelope(t, .008, .09)
    return dict(flow=water(timebase(4.8), loop=True), valve=valve, leak=leak,
                success=success, place=metal(.56, 670), repair=metal(.61, 500),
                undo=metal(.41, 410), dry=metal(.32, 235))


def pcm(samples):
    return np.rint(np.clip(samples, -.99, .99) * 32767).astype('<i2').tobytes()


def audition(sounds, destination):
    track = np.zeros(12 * RATE)
    for offset in [.2, .52, .86]:
        mix(track, sounds['place'], offset)
    for offset, end, result in [(1.3, 5.8, 'success'), (7.0, 10.7, 'leak')]:
        mix(track, sounds['valve'], offset)
        t = timebase(end - offset)
        mix(track, sounds['flow'][:len(t)] * envelope(t, .24, .13), offset)
        mix(track, sounds[result], end)
    with wave.open(str(destination), 'wb') as output:
        output.setparams((1, 2, RATE, 0, 'NONE', 'not compressed'))
        output.writeframes(pcm(track * .78))


def mix(track, clip, offset):
    start = round(offset * RATE)
    track[start:start + len(clip)] += clip


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--audition', type=Path)
    args = parser.parse_args()
    clips = make_sounds()
    bank = {'rate': RATE, 'samples': {name: base64.b64encode(pcm(clip)).decode() for name, clip in clips.items()}}
    target = ROOT / 'app/src/main/assets/jspp/pump-sounds.js'
    target.write_text('// Generated by tools/render/design_sounds.py\nvar PumpSounds = ' +
                      json.dumps(bank, separators=(',', ':')) + ';\n', encoding='utf-8')
    if args.audition:
        audition(clips, args.audition)
